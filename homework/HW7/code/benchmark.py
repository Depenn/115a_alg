"""
Benchmark: LCS dynamic programming vs. Myers O(ND) on synthetic file pairs.

Three scenarios, chosen to expose the strengths and the weakness of each
algorithm:

    identical  : B is a copy of A            (D = 0,      best case for Myers)
    similar    : B = A with ~1% of the lines replaced
                 (D ~ 2*N/100, the typical `git diff` situation)
    different  : A and B are unrelated       (D ~ N + M,  worst case for Myers)

For each scenario we grow N and time both algorithms.  Myers' trace in
this implementation stores O(D^2) memory, so the "different" scenario is
capped at N = 1000 (D ~ 2000 already means ~2 million trace entries);
that limitation is itself one of the findings of the report.

Output: markdown tables, written to benchmark_results.md next to this file.

Run:  python benchmark.py
"""

import random
import time
import tracemalloc
from pathlib import Path

from lcs_diff import diff as lcs_diff_ops
from myers_diff import diff as myers_diff_ops

HERE = Path(__file__).resolve().parent

DP_MAX_N = 4000           # DP is Theta(N*M): 4000^2 = 16M cells is plenty of evidence
SCENARIOS = {
    "identical": [500, 1000, 2000, 4000, 8000, 16000],
    "similar":   [500, 1000, 2000, 4000, 8000, 16000],
    "different": [250, 500, 1000],
}
MEMORY_SIZES = {"identical": 2000, "similar": 2000, "different": 1000}


def gen_lines(n, rng):
    """Random, essentially unique lines (like real source code)."""
    return [f"line {rng.randrange(16 ** 8):08x}" for _ in range(n)]


def make_pair(scenario, n, rng):
    a = gen_lines(n, rng)
    if scenario == "identical":
        b = list(a)
    elif scenario == "similar":
        b = list(a)
        for _ in range(max(1, n // 100)):          # replace ~1% of the lines
            b[rng.randrange(n)] = f"line {rng.randrange(16 ** 8):08x}"
    elif scenario == "different":
        b = gen_lines(n, rng)
    else:
        raise ValueError(scenario)
    return a, b


def timeit(algo, a, b, repeats):
    best = float("inf")
    ops = None
    for _ in range(repeats):
        t0 = time.perf_counter()
        ops = algo(a, b)
        best = min(best, time.perf_counter() - t0)
    edits = sum(1 for op, _ in ops if op != " ")
    return best, edits


def measure_peak(algo, a, b):
    tracemalloc.start()
    algo(a, b)
    _, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return peak


def fmt_bytes(n):
    return f"{n / 1024 / 1024:.1f} MB"


def fmt_time(t):
    return f"{t * 1000:.1f} ms" if t < 1 else f"{t:.2f} s"


def main():
    rng = random.Random(20261021)
    lines_out = []
    memory_rows = {}

    def emit(s=""):
        print(s)
        lines_out.append(s)

    emit("# Benchmark results (auto-generated by `python benchmark.py`)")
    emit()
    emit(f"Python {__import__('sys').version.split()[0]}, "
         "best of 3 runs for N <= 1000, single run otherwise.")

    for scenario, sizes in SCENARIOS.items():
        emit()
        if scenario == "identical":
            emit("## Scenario `identical`: B is a copy of A (D = 0)")
        elif scenario == "similar":
            emit("## Scenario `similar`: B = A with ~1% of lines replaced "
                 "(the typical `git diff` case)")
        else:
            emit("## Scenario `different`: A and B unrelated (D ~ N + M, "
                 "Myers' worst case)")
        emit()
        emit("| N (lines) | LCS-DP | Myers | Speedup (DP / Myers) | SES length D |")
        emit("|---:|---:|---:|---:|---:|")

        for n in sizes:
            a, b = make_pair(scenario, n, rng)
            repeats = 3 if n <= 1000 else 1

            t_dp = t_my = None
            d_len = None

            if n <= DP_MAX_N:
                t_dp, d_dp = timeit(lcs_diff_ops, a, b, repeats)
                d_len = d_dp
            t_my, d_my = timeit(myers_diff_ops, a, b, repeats)

            if d_len is None:
                d_len = d_my
            assert d_len == d_my, "algorithms disagree on the edit distance!"

            dp_cell = fmt_time(t_dp) if t_dp is not None else "n/a"
            sp = f"{t_dp / t_my:.1f}x" if t_dp is not None else "n/a"
            emit(f"| {n:,} | {dp_cell} | {fmt_time(t_my)} | {sp} | {d_len:,} |")

            print(f"  [{scenario}] N={n:<6} done (D={d_len})")

        # Peak-memory comparison at one representative size.
        n = MEMORY_SIZES[scenario]
        a, b = make_pair(scenario, n, rng)
        peak_dp = peak_my = None
        if n <= DP_MAX_N:
            peak_dp = measure_peak(lcs_diff_ops, a, b)
        peak_my = measure_peak(myers_diff_ops, a, b)
        memory_rows[scenario] = (n, peak_dp, peak_my)
        print(f"  [{scenario}] N={n:<6} memory done")

    emit()
    emit("## Peak memory (tracemalloc) at a representative size")
    emit()
    emit("| Scenario | N | LCS-DP | Myers |")
    emit("|---|---:|---:|---:|")
    for scenario, (n, peak_dp, peak_my) in memory_rows.items():
        dp_cell = fmt_bytes(peak_dp) if peak_dp is not None else "n/a"
        emit(f"| {scenario} | {n:,} | {dp_cell} | {fmt_bytes(peak_my)} |")

    out_path = HERE / "benchmark_results.md"
    out_path.write_text("\n".join(lines_out) + "\n", encoding="utf-8")
    print(f"\nResults written to {out_path}")


if __name__ == "__main__":
    main()
